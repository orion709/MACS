CREATE TABLE IF NOT EXISTS SERVERS (
    CONFIG_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    TITLE TEXT NOT NULL,
    SERVER_IP TEXT NOT NULL,
    SERVER_PORT INTEGER NOT NULL,
    SERVER_NAME TEXT NOT NULL,
    SERVER_PASSWORD TEXT,
    SERVER_KEY_NAME TEXT,
    SERVER_KEY_FULL TEXT
);
CREATE TABLE IF NOT EXISTS ACTIVE_CONNECTIONS (
    CONNECTIONS_ID INTEGER NOT NULL,
    SERVER_CONFIG_ID INTEGER NO NULL,
    FOREIGH KEY (SERVER_CONFIG_ID)
        REFERENCES SERVERS(CONFIG_ID)
        ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS WINDOWS_OF_CONNECTIONS (
    WINDOWS_ID INTEGER NOT NULL,
    CONNECTION_ID INTEGER NOT NULL,
    CONTINUE_AFTER TEXT,
    FOREIGH KEY (CONNECTION_ID)
        REFERENCES ACTIVE_CONNECTIONS(CONNECTIONS_ID)
        ON DELETE CASCADE
)
